/**
 * Turns an eHive XML report into SQL that loads the museum's existing records
 * into the ehive_records reference table.
 *
 *   node scripts/import-ehive-xml.mjs ../eHive_reports/secondreport_xml_*.xml
 *   npx wrangler d1 execute artefact-catalogue --remote --file=seeds/seed-ehive.sql
 *
 * WHY A FILE AND NOT THE API. eHive's REST API needs credentials this museum
 * can't get, and returns public fields for public records only - every record in
 * this collection is currently unpublished, so the API would have returned
 * nothing at all. The XML report a person downloads from their own account has
 * more in it than the API would ever have given us, including eHive's own record
 * ids, which are what make it possible to update those records later rather than
 * duplicating them.
 *
 * Deliberately no XML library: the report's shape is flat and regular, and a
 * dependency added for one script is a dependency someone has to maintain. If the
 * shape ever stops being regular this will throw rather than quietly skip, which
 * is the behaviour you want when the input is a museum's catalogue.
 *
 * Rerunnable: the table is emptied first, because a partial merge of somebody
 * else's master data is a good way to invent records that exist in neither system.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
// Deliberately NOT in migrations/: wrangler treats every file in that directory
// as a migration and ordered this one BEFORE the migration that creates the table
// it writes to, which failed outright. Seeds are data, not schema changes.
const OUT_PATH = resolve(root, "seeds/seed-ehive.sql");

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/import-ehive-xml.mjs <ehive-report.xml>");
  process.exit(1);
}

const xml = readFileSync(resolve(process.cwd(), input), "utf8");

/** SQL escapes a quote by doubling it. Getting this wrong loads a truncated value. */
const q = (v) =>
  v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;

const unescape = (s) =>
  s
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, "$1")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .trim();

const accountId = (xml.match(/<accountId>([^<]*)<\/accountId>/) || [])[1] ?? "";
const description = unescape((xml.match(/<description>([^<]*)<\/description>/) || [])[1] ?? "");

const records = [];
const recordPattern = /<record\b([^>]*)>([\s\S]*?)<\/record>/g;
let match;
while ((match = recordPattern.exec(xml)) !== null) {
  const attrs = match[1];
  const body = match[2];

  const attr = (name) => (attrs.match(new RegExp(`${name}="([^"]*)"`)) || [])[1] ?? null;

  // Every field in the record, flattened. eHive nests fields inside fieldSets,
  // but the names are unique across the record so the nesting carries no meaning
  // we need here.
  const fields = {};
  const fieldPattern = /<field>([\s\S]*?)<\/field>/g;
  let f;
  while ((f = fieldPattern.exec(body)) !== null) {
    const name = (f[1].match(/<fieldName>([\s\S]*?)<\/fieldName>/) || [])[1];
    const value = (f[1].match(/<fieldValue>([\s\S]*?)<\/fieldValue>/) || [])[1];
    if (!name) continue;
    const clean = value ? unescape(value) : "";
    if (!clean) continue;
    // A repeated field name keeps every value rather than the last one.
    fields[unescape(name)] = fields[unescape(name)]
      ? `${fields[unescape(name)]}; ${clean}`
      : clean;
  }

  const id = attr("object_record_id");
  if (!id) throw new Error("A record has no object_record_id. Refusing to guess.");

  records.push({
    object_record_id: id,
    perspective: attr("perspective"),
    public_access: attr("public_access"),
    fields,
  });
}

if (records.length === 0) throw new Error("No records found. Is this an eHive XML report?");

const lines = [
  `-- Existing eHive records for account ${accountId} (${description}).`,
  `-- Generated by scripts/import-ehive-xml.mjs from ${basename(input)}.`,
  `-- ${records.length} records. Regenerate rather than editing by hand.`,
  "",
  "DELETE FROM ehive_records;",
  "",
];

for (const r of records) {
  const f = r.fields;
  lines.push(
    `INSERT INTO ehive_records (object_record_id, object_number, name, object_type, ` +
      `place_made, maker, location, perspective, public_access, fields_json, source_file) VALUES (` +
      [
        q(r.object_record_id),
        q(f.object_number),
        q(f.name),
        q(f.object_type),
        q(f.place_made),
        q(f.primary_creator_maker),
        q(f.location),
        q(r.perspective),
        r.public_access === null ? "NULL" : Number(r.public_access),
        q(JSON.stringify(f)),
        q(basename(input)),
      ].join(", ") +
      ");"
  );
}

writeFileSync(OUT_PATH, lines.join("\n") + "\n");

const withNumber = records.filter((r) => r.fields.object_number).length;
console.log(`${records.length} records from account ${accountId} (${description})`);
console.log(`  ${withNumber} carry an object number`);
console.log(`  wrote ${OUT_PATH}`);
console.log("\nNow run:");
console.log("  npx wrangler d1 execute artefact-catalogue --remote --file=seeds/seed-ehive.sql");
